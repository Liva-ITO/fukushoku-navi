export const greeting = (name: string, hour: number): string => {
  if (hour >= 5 && hour < 10) return `おはようございます、${name}さん`;
  if (hour >= 10 && hour < 18) return `こんにちは、${name}さん`;
  if (hour >= 18) return `こんばんは、${name}さん`;
  return `こんばんは、${name}さん。ゆっくりで大丈夫です`;
};

